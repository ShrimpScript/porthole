# The site kit's .i-<name> masks -> symbol. The brand marks (claude, github, tailscale, tmux) stay.
KIT = {
    "add": "add", "back": "arrow_back", "build": "build", "check": "check", "close": "close",
    "description": "description", "diff": "difference", "download": "download", "edit": "edit",
    "inbox": "inbox", "info": "info", "language": "language", "more": "more_horiz",
    "next": "chevron_right", "pause": "pause", "play": "play_arrow", "prev": "chevron_left",
    "refresh": "refresh", "search": "search", "send": "send", "settings": "settings",
    "terminal": "terminal", "up": "arrow_upward", "warning": "warning",
}


def path_of(name, cache):
    f = os.path.join(cache, name + ".svg")
    if not os.path.exists(f):
        with urllib.request.urlopen(URL.format(c=COMMIT, n=name), timeout=30) as r:
            data = r.read()
        with open(f, "wb") as o:
            o.write(data)
    svg = open(f, encoding="utf-8").read()
    if 'viewBox="0 -960 960 960"' not in svg:
        sys.exit(f"{name}: unexpected viewBox")
    paths = re.findall(r'<path d="([^"]+)"', svg)
    if len(paths) != 1:
        sys.exit(f"{name}: expected one path, found {len(paths)}")
    return paths[0]


def write_kotlin(root, cache):
    out = [
        "package dev.shrimpscript.porthole.ui",
        "",
        "import androidx.compose.ui.graphics.Color",
        "import androidx.compose.ui.graphics.SolidColor",
        "import androidx.compose.ui.graphics.vector.ImageVector",
        "import androidx.compose.ui.graphics.vector.addPathNodes",
        "import androidx.compose.ui.unit.dp",
        "",
        "/*",
        " * The app's icons: one set, Material Symbols Rounded at weight 400, unfilled (Apache 2.0,",
        " * Google). Generated by tools/glyphs.py from google/material-design-icons at",
        f" * {COMMIT[:12]}; do not edit by hand. Names follow the Material Icons they replaced.",
        " */",
        "object Symbols {",
    ]
    for kt in sorted(APP):
        sym, mirror = APP[kt]
        d = path_of(sym, cache)
        m = ", mirror = true" if mirror else ""
        out.append(f'    val {kt}: ImageVector by lazy {{ glyph("{kt}", "{d}"{m}) }}')
    out += [
        "}",
        "",
        "/** A 24dp icon from its path in the symbols' 960-unit square, whose top edge is at y = -960. */",
        "private fun glyph(name: String, d: String, mirror: Boolean = false): ImageVector =",
        "    ImageVector.Builder(name, 24.dp, 24.dp, 960f, 960f, autoMirror = mirror)",
        "        .addGroup(translationY = 960f)",
        "        .addPath(addPathNodes(d), fill = SolidColor(Color.Black))",
        "        .clearGroup()",
        "        .build()",
        "",
    ]
    p = os.path.join(root, "app-android/app/src/main/java/dev/shrimpscript/porthole/ui/Symbols.kt")
    # Only ever replace a file this script wrote.
    if os.path.exists(p) and "Generated by tools/glyphs.py" not in open(p, encoding="utf-8").read():
        sys.exit(f"{p} exists and was not written by this script; not overwriting it")
    open(p, "w", encoding="utf-8").write("\n".join(out))
    print("wrote", p, len(APP), "icons")


def write_kit(root, cache):
    p = os.path.join(root, "site/assets/kit.css")
    css = open(p, encoding="utf-8").read()
    for cls, sym in KIT.items():
        d = path_of(sym, cache)
        svg = f"<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 -960 960 960'><path d='{d}'/></svg>"
        uri = urllib.parse.quote(svg, safe="/:=' -.,")
        line = re.compile(r'^\.i-' + re.escape(cls) + r' \{ --m: url\("data:image/svg\+xml,[^"]*"\); \}$', re.M)
        new = f'.i-{cls} {{ --m: url("data:image/svg+xml,{uri}"); }}'
        css, n = line.subn(lambda _: new, css)
        if n != 1:
            sys.exit(f"kit.css: .i-{cls} found {n} times")
    open(p, "w", encoding="utf-8").write(css)
    print("wrote", p, len(KIT), "masks")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--cache", default=os.path.join(tempfile.gettempdir(), "porthole-glyphs"))
    a = ap.parse_args()
    os.makedirs(a.cache, exist_ok=True)
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    write_kotlin(root, a.cache)
    write_kit(root, a.cache)


if __name__ == "__main__":
    main()
