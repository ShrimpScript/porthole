"""The app's icons, and the site kit's copies of them, from Material Symbols Rounded.

One set: Material Symbols, Rounded, weight 400, unfilled (Apache 2.0, Google), pinned to one
commit of google/material-design-icons. Writes

  app-android/app/src/main/java/dev/shrimpscript/porthole/ui/Symbols.kt  (ImageVectors)
  site/assets/kit.css                                                     (the .i-* masks)

Run from the repo root:  python3 tools/glyphs.py [--cache DIR]
"""
